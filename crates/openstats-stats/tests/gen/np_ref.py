"""Reference values for tests/nonparametric.rs (SciPy / NumPy / brute-force enumeration).

Run: python3 np_ref.py > ../common/np_data.rs

* Wilcoxon / Mann-Whitney p-values: scipy.stats.wilcoxon / mannwhitneyu (exact and asymptotic).
* Hodges-Lehmann intervals: brute-force enumeration of all sign patterns / all rank arrangements.
* Kruskal-Wallis, Friedman, Mood's median: scipy.stats.kruskal / friedmanchisquare / median_test.
* Sign test: scipy.stats.binom tails.  Runs test: enumeration of every arrangement.
"""
import itertools
import numpy as np
from scipy import stats

rng = np.random.default_rng(20261119)


def arr(name, a):
    return f"pub const {name}: &[f64] = &[{', '.join(repr(float(v)) for v in np.ravel(a))}];\n"


def sc(name, v):
    return f"pub const {name}: f64 = {float(v)!r};\n"


def hl_ci_exact_signrank(n, alpha2):
    """c = largest k with P(W <= k) <= alpha2 by enumerating all 2^n sign patterns."""
    counts = np.zeros(n * (n + 1) // 2 + 1)
    for mask in range(1 << n):
        s = sum(i + 1 for i in range(n) if mask >> i & 1)
        counts[s] += 1
    cdf = np.cumsum(counts) / 2 ** n
    c = -1
    for k, v in enumerate(cdf):
        if v <= alpha2 + 1e-12:
            c = k
        else:
            break
    achieved = 1 - 2 * (cdf[c] if c >= 0 else 0)
    return c, achieved


def hl_ci_exact_mw(m, n, alpha2):
    N = m + n
    counts = {}
    for comb in itertools.combinations(range(1, N + 1), m):
        u = sum(comb) - m * (m + 1) // 2
        counts[u] = counts.get(u, 0) + 1
    tot = sum(counts.values())
    cdf, acc = {}, 0
    for u in range(m * n + 1):
        acc += counts.get(u, 0)
        cdf[u] = acc / tot
    c = -1
    for u in range(m * n + 1):
        if cdf[u] <= alpha2 + 1e-12:
            c = u
        else:
            break
    achieved = 1 - 2 * (cdf[c] if c >= 0 else 0)
    return c, achieved


out = "// Generated by tests/gen/np_ref.py (NumPy %s, SciPy %s). Do not edit.\n#![allow(clippy::approx_constant, clippy::excessive_precision)]\n" % (np.__version__, stats.__version__ if hasattr(stats, '__version__') else '')

# ---------------------------------------------------------------- sign test
x = np.round(rng.normal(5.0, 2.0, 15), 2)
out += arr("SIGN_X", x)
m0 = 3.6
above = int((x > m0).sum()); below = int((x < m0).sum()); m = above + below
out += sc("SIGN_M0", m0)
out += f"pub const SIGN_ABOVE: usize = {above};\npub const SIGN_BELOW: usize = {below};\n"
out += sc("SIGN_P_TWO", min(1, 2 * min(stats.binom.cdf(above, m, .5), stats.binom.sf(above - 1, m, .5))))
out += sc("SIGN_P_GREATER", stats.binom.sf(above - 1, m, .5))
out += sc("SIGN_P_LESS", stats.binom.cdf(above, m, .5))
n = len(x)
xs = np.sort(x)
best = None
for r in range(1, (n + 1) // 2 + 1):
    conf = 1 - 2 * stats.binom.cdf(r - 1, n, .5)
    if conf >= 0.95 - 1e-12:
        best = (r, conf)
r, conf = best
out += sc("SIGN_CI_LO", xs[r - 1]) + sc("SIGN_CI_HI", xs[n - r]) + sc("SIGN_CI_CONF", conf)

# ---------------------------------------------------------------- Wilcoxon signed rank
# (a) no ties, exact
d = np.round(rng.normal(0.8, 1.5, 13), 3)
out += arr("WSR_D", d)
wplus = float(stats.rankdata(np.abs(d))[d > 0].sum())
out += sc("WSR_WPLUS", wplus)
out += sc("WSR_P_TWO", stats.wilcoxon(d, method='exact').pvalue)
out += sc("WSR_P_GREATER", stats.wilcoxon(d, method='exact', alternative='greater').pvalue)
out += sc("WSR_P_LESS", stats.wilcoxon(d, method='exact', alternative='less').pvalue)
walsh = np.sort([(d[i] + d[j]) / 2 for i in range(len(d)) for j in range(i, len(d))])
out += sc("WSR_HL", np.median(walsh))
c, ach = hl_ci_exact_signrank(len(d), 0.025)
M = len(walsh)
out += sc("WSR_CI_LO", walsh[c]) + sc("WSR_CI_HI", walsh[M - 1 - c]) + sc("WSR_CI_ACH", ach)
# (b) ties and zeros, normal approximation, with and without continuity correction
t = np.array([1.0, 2.0, 2.0, 3.0, 0.0, -1.0, 4.0, 4.0, 4.0, -2.0, 5.0, 0.0, 6.5, 7.0, -3.0, 2.0, 8.0, 9.0, 1.5, 3.5])
out += arr("WSR_T", t)
nz = t[t != 0]
out += sc("WSR_T_WPLUS", float(stats.rankdata(np.abs(nz))[nz > 0].sum()))
for cc in (False, True):
    r = stats.wilcoxon(t, method='approx', correction=cc, zero_method='wilcox')
    tag = "CC" if cc else "NOCC"
    out += sc(f"WSR_T_P_{tag}", r.pvalue)
    r = stats.wilcoxon(t, method='approx', correction=cc, zero_method='wilcox', alternative='greater')
    out += sc(f"WSR_T_PG_{tag}", r.pvalue)

# ---------------------------------------------------------------- Mann-Whitney
a = np.round(rng.normal(10, 2, 9), 2)
b = np.round(rng.normal(12, 2, 8), 2)
out += arr("MW_A", a) + arr("MW_B", b)
ur = stats.mannwhitneyu(a, b, method='exact')
out += sc("MW_U", stats.mannwhitneyu(a, b, method='exact', alternative='greater').statistic)
out += sc("MW_P_TWO", ur.pvalue)
out += sc("MW_P_GREATER", stats.mannwhitneyu(a, b, method='exact', alternative='greater').pvalue)
out += sc("MW_P_LESS", stats.mannwhitneyu(a, b, method='exact', alternative='less').pvalue)
diffs = np.sort([p - q for p in a for q in b])
out += sc("MW_HL", np.median(diffs))
c, ach = hl_ci_exact_mw(len(a), len(b), 0.025)
out += sc("MW_CI_LO", diffs[c]) + sc("MW_CI_HI", diffs[len(diffs) - 1 - c]) + sc("MW_CI_ACH", ach)
# with ties, asymptotic
ta = np.array([1, 2, 2, 3, 4, 4, 5, 6, 6, 7], float)
tb = np.array([2, 3, 3, 5, 7, 8, 8, 9, 9, 10, 11], float)
out += arr("MW_TA", ta) + arr("MW_TB", tb)
for cc in (False, True):
    tag = "CC" if cc else "NOCC"
    r = stats.mannwhitneyu(ta, tb, method='asymptotic', use_continuity=cc)
    out += sc(f"MW_T_P_{tag}", r.pvalue)
    r = stats.mannwhitneyu(ta, tb, method='asymptotic', use_continuity=cc, alternative='less')
    out += sc(f"MW_T_PL_{tag}", r.pvalue)
out += sc("MW_T_U", stats.mannwhitneyu(ta, tb, method='asymptotic').statistic)

# ---------------------------------------------------------------- Kruskal-Wallis, Mood, Friedman
g1 = np.array([27, 2, 4, 18, 7, 9], float)
g2 = np.array([20, 8, 14, 36, 21, 22], float)
g3 = np.array([34, 31, 3, 23, 30, 6], float)
g4 = np.array([6, 9, 12, 12, 15, 20, 25], float)  # ties with others
groups = [g1, g2, g3, g4]
out += arr("KW_G1", g1) + arr("KW_G2", g2) + arr("KW_G3", g3) + arr("KW_G4", g4)
kw = stats.kruskal(*groups)
out += sc("KW_H_ADJ", kw.statistic) + sc("KW_P_ADJ", kw.pvalue)
allv = np.concatenate(groups)
rk = stats.rankdata(allv)
N = len(allv)
h = 12 / (N * (N + 1)) * sum(r.sum() ** 2 / len(r) for r in np.split(rk, np.cumsum([len(g) for g in groups])[:-1])) - 3 * (N + 1)
out += sc("KW_H", h) + sc("KW_P", stats.chi2.sf(h, 3))
offs = np.cumsum([0] + [len(g) for g in groups])
out += arr("KW_MEANRANK", [rk[offs[i]:offs[i + 1]].mean() for i in range(4)])
out += arr("KW_Z", [(rk[offs[i]:offs[i + 1]].mean() - (N + 1) / 2) / np.sqrt((N + 1) * (N - len(groups[i])) / (12 * len(groups[i]))) for i in range(4)])

mm = stats.median_test(*groups, ties='below', correction=False)
out += sc("MOOD_STAT", mm[0]) + sc("MOOD_P", mm[1]) + sc("MOOD_MED", mm[2])
out += arr("MOOD_TABLE", mm[3])  # 2 x k row-major: above, below

fr = np.round(rng.normal(0, 1, (10, 4)) + np.array([0, 0.5, 1.0, 1.5]), 1)
fr[2, 1] = fr[2, 2]  # a tie inside a block
fr[5, 0] = fr[5, 3]
out += arr("FR_DATA", fr)
f = stats.friedmanchisquare(*fr.T)
out += sc("FR_S_ADJ", f.statistic) + sc("FR_P_ADJ", f.pvalue)
b, k = fr.shape
ranks = np.apply_along_axis(stats.rankdata, 1, fr)
S = 12 / (b * k * (k + 1)) * (ranks.sum(0) ** 2).sum() - 3 * b * (k + 1)
out += sc("FR_S", S) + sc("FR_P", stats.chi2.sf(S, k - 1)) + arr("FR_RANKSUM", ranks.sum(0))
grand = np.median(fr)
adj = fr - np.median(fr, axis=1, keepdims=True) + grand
out += arr("FR_EST", np.median(adj, axis=0))

# ---------------------------------------------------------------- runs test
seq = np.array([3, 5, 2, 7, 8, 1, 9, 4, 6, 10, 2, 12, 11, 1, 5, 8, 9, 3, 2, 13, 4, 7], float)
K = 6.5
out += arr("RUNS_X", seq) + sc("RUNS_K", K)
s = seq > K
n1, n2 = int(s.sum()), int((~s).sum())
runs = 1 + int((s[1:] != s[:-1]).sum())
out += f"pub const RUNS_N1: usize = {n1};\npub const RUNS_N2: usize = {n2};\npub const RUNS_R: usize = {runs};\n"
Nn = n1 + n2
mu = 1 + 2 * n1 * n2 / Nn
var = 2 * n1 * n2 * (2 * n1 * n2 - Nn) / (Nn ** 2 * (Nn - 1))
z = (runs - mu) / np.sqrt(var)
out += sc("RUNS_Z", z) + sc("RUNS_P_NORM", 2 * stats.norm.sf(abs(z)))
dist = {}
for comb in itertools.combinations(range(Nn), n1):
    arrg = np.zeros(Nn, bool)
    arrg[list(comb)] = True
    r = 1 + int((arrg[1:] != arrg[:-1]).sum())
    dist[r] = dist.get(r, 0) + 1
tot = sum(dist.values())
lo = sum(v for r, v in dist.items() if r <= runs) / tot
hi = sum(v for r, v in dist.items() if r >= runs) / tot
out += sc("RUNS_P_EXACT", min(1, 2 * min(lo, hi)))
print(out)
