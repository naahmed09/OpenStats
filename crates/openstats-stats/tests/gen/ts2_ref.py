"""Reference values for tests/unitroot.rs. Run: python3 ts2_ref.py > ../common/ts2_data.rs

Independent NumPy implementations of the ADF regression (fixed lag and AIC lag choice on the common sample),
KPSS (Bartlett long-run variance) and the cross-correlation function. The MacKinnon critical-value surfaces are
checked by Monte Carlo inside this generator (assertion within 0.06 of the simulated quantile).
"""
import numpy as np

rng = np.random.default_rng(31337)


def arr(name, a):
    return f"pub const {name}: &[f64] = &[{', '.join(repr(float(v)) for v in np.ravel(a))}];\n"


def sc(name, v):
    return f"pub const {name}: f64 = {float(v)!r};\n"


def adf_stat(y, det, lags, start):
    dy = np.diff(y)
    rows, resp = [], []
    for t in range(start, len(dy)):
        r = [y[t]]
        if det >= 1:
            r.append(1.0)
        if det == 2:
            r.append(t + 1.0)
        r += [dy[t - l] for l in range(1, lags + 1)]
        rows.append(r)
        resp.append(dy[t])
    X, z = np.array(rows), np.array(resp)
    beta, *_ = np.linalg.lstsq(X, z, rcond=None)
    res = z - X @ beta
    n, k = X.shape
    s2 = res @ res / (n - k)
    cov = s2 * np.linalg.inv(X.T @ X)
    return beta[0], np.sqrt(cov[0, 0]), res @ res, n, k


def adf_auto(y, det):
    n = len(y)
    maxlag = min(int(np.ceil(12 * (n / 100) ** 0.25)), (n - 1) // 2 - 2)
    best = None
    for l in range(maxlag + 1):
        _, _, ssr, nn, k = adf_stat(y, det, l, maxlag)
        aic = nn * np.log(ssr / nn) + 2 * k
        if best is None or aic < best[1]:
            best = (l, aic)
    return best[0]


def kpss(y, trend, l):
    n = len(y)
    t = np.arange(1, n + 1.0)
    X = np.column_stack([np.ones(n), t]) if trend else np.ones((n, 1))
    beta, *_ = np.linalg.lstsq(X, y, rcond=None)
    e = y - X @ beta
    S = np.cumsum(e)
    lrv = e @ e / n
    for k in range(1, l + 1):
        lrv += 2 * (1 - k / (l + 1)) * (e[k:] @ e[:-k]) / n
    return (S @ S) / (n * n * lrv)


# data: random walk (unit root), AR(1) stationary, trend-stationary
n = 120
rw = np.cumsum(rng.normal(0, 1, n)) + 5
ar = np.zeros(n)
for i in range(1, n):
    ar[i] = 0.6 * ar[i - 1] + rng.normal()
tr = 0.05 * np.arange(n) + ar
out = "// Generated by tests/gen/ts2_ref.py -- do not edit.\n"
for name, y in (("RW", rw), ("AR", ar), ("TR", tr)):
    out += arr(f"U_{name}", y)
for name, y in (("RW", rw), ("AR", ar), ("TR", tr)):
    for det, dn in ((0, "N"), (1, "C"), (2, "T")):
        g, se, _, nobs, _ = adf_stat(y, det, 2, 2)
        out += sc(f"ADF_{name}_{dn}_FIX", g / se)
        l = adf_auto(y, det)
        g, se, _, nobs, _ = adf_stat(y, det, l, l)
        out += sc(f"ADF_{name}_{dn}_AUTO", g / se) + sc(f"ADF_{name}_{dn}_AUTOLAG", l)
for name, y in (("RW", rw), ("AR", ar), ("TR", tr)):
    for trend, tn in ((False, "L"), (True, "T")):
        for lg, ln in ((4, "S"), (int(np.ceil(12 * (n / 100) ** 0.25)), "LONG")):
            out += sc(f"KPSS_{name}_{tn}_{ln}", kpss(y, trend, lg))
x = rng.normal(0, 1, 80)
yv = np.roll(x, 3) * 0.8 + rng.normal(0, 0.5, 80)
out += arr("CCF_X", x) + arr("CCF_Y", yv)
mx, my = x.mean(), yv.mean()
sx, sy = x.std(), yv.std()
cc = []
for k in range(-6, 7):
    s = sum((x[t] - mx) * (yv[t + k] - my) for t in range(80) if 0 <= t + k < 80)
    cc.append(s / (80 * sx * sy))
out += arr("CCF_REF", cc)

dr = np.cumsum(rng.normal(0.3, 1, 150))
out += arr("U_DR", dr)

# Monte Carlo check of the critical values (n = 100, lag 0, 12000 replications)
sim = {0: [], 1: [], 2: []}
for _ in range(12000):
    y = np.cumsum(rng.normal(0, 1, 100))
    for det in (0, 1, 2):
        g, se, *_ = adf_stat(y, det, 0, 0)
        sim[det].append(g / se)
coef = {
    0: [[-2.56574, -2.2358, -3.627, 0.0], [-1.94100, -0.2686, -3.365, 31.223], [-1.61682, 0.2656, -2.714, 25.364]],
    1: [[-3.43035, -6.5393, -16.786, -79.433], [-2.86154, -2.8903, -4.234, -40.040], [-2.56677, -1.5384, -2.809, 0.0]],
    2: [[-3.95877, -9.0531, -28.428, -134.155], [-3.41049, -4.3904, -9.036, -45.374], [-3.12705, -2.5856, -3.925, -22.380]],
}
N = 99.0
for det in (0, 1, 2):
    for i, q in enumerate((0.01, 0.05, 0.10)):
        c = coef[det][i]
        f = c[0] + c[1] / N + c[2] / N ** 2 + c[3] / N ** 3
        mc = np.quantile(sim[det], q)
        assert abs(f - mc) < 0.06, (det, q, f, mc)
        import sys
        print(f"// MC check det={det} q={q}: surface {f:.3f} vs simulated {mc:.3f}", file=sys.stderr)
print(out, end="")
