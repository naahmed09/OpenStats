"""Reference values for tests/anova_random.rs (NumPy / SciPy only).

Run: python3 anova_ref.py > ../common/anova2_data.rs
  * Unbalanced random-factor and nested ANOVA: adjusted sums of squares and the
    expected-mean-square coefficients tr(P_i Z_j Z_j')/df_i from dense projection matrices.
  * Linear mixed model: independent dense REML / ML (scipy L-BFGS-B on log variances),
    GLS fixed effects, and Satterthwaite degrees of freedom from a finite-difference Hessian.
"""
import numpy as np
from scipy import linalg, optimize

rng = np.random.default_rng(20261119)
out = ["// Generated by tests/gen/anova_ref.py (NumPy, SciPy). Do not edit.\n",
       "#![allow(clippy::approx_constant, clippy::excessive_precision)]\n"]


def arr(name, a):
    flat = ", ".join(repr(float(v)) for v in np.ravel(a))
    out.append(f"pub const {name}: &[f64] = &[{flat}];\n")


def idx(name, a):
    flat = ", ".join(str(int(v)) for v in np.ravel(a))
    out.append(f"pub const {name}: &[usize] = &[{flat}];\n")


def proj(X):
    Q = linalg.orth(X, rcond=1e-10)
    return Q @ Q.T


def sumzero(idxs, L):
    M = np.zeros((len(idxs), L - 1))
    for r, i in enumerate(idxs):
        if i < L - 1:
            M[r, i] = 1.0
        else:
            M[r, :] = -1.0
    return M


# ---------------------------------------------------------------- unbalanced A (fixed) x B (random)
A, B = [], []
for a in range(3):
    for b in range(4):
        for _ in range(int(rng.integers(1, 4))):
            A.append(a)
            B.append(b)
A = np.array(A)
B = np.array(B)
n = len(A)
y = np.round(10 + np.array([0.0, 1.5, -1.0])[A] + rng.normal(0, 1.2, 4)[B] + rng.normal(0, 0.8, n), 3)
XA = sumzero(A, 3)
XB = sumzero(B, 4)
XAB = np.hstack([XA[:, [i]] * XB[:, [j]] for i in range(2) for j in range(3)])
X = np.hstack([np.ones((n, 1)), XA, XB, XAB])
cols = {"A": range(1, 3), "B": range(3, 6), "AB": range(6, 12)}
P = proj(X)
ss, df, cB, cAB = [], [], [], []
ZB = np.eye(4)[B]
cell = A * 4 + B
ZAB = np.eye(12)[cell]
for term in ["A", "B", "AB"]:
    keep = [j for j in range(X.shape[1]) if j not in cols[term]]
    Pr = proj(X[:, keep])
    Pi = P - Pr
    d = round(np.trace(Pi))
    ss.append(y @ Pi @ y)
    df.append(d)
    cB.append(np.trace(Pi @ ZB @ ZB.T) / d)
    cAB.append(np.trace(Pi @ ZAB @ ZAB.T) / d)
idx("UB_A", A)
idx("UB_B", B)
arr("UB_Y", y)
arr("UB_SS", ss)
arr("UB_DF", df)
arr("UB_COEF_B", cB)
arr("UB_COEF_AB", cAB)
arr("UB_SSE", y @ y - y @ P @ y)

# ---------------------------------------------------------------- unbalanced fully nested
T, M, L, yy = [], [], [], []
mid_id = 0
for t in range(3):
    for m in range(int(rng.integers(2, 4))):
        for l in range(int(rng.integers(2, 4))):
            for _ in range(int(rng.integers(1, 4))):
                T.append(t)
                M.append(mid_id)
                L.append(mid_id * 10 + l)
        mid_id += 1
T = np.array(T)
M = np.array(M)
Lc = np.unique(L, return_inverse=True)[1]
n = len(T)
yy = np.round(50 + rng.normal(0, 3, 3)[T] + rng.normal(0, 2, M.max() + 1)[M] + rng.normal(0, 1.5, Lc.max() + 1)[Lc]
              + rng.normal(0, 1, n), 3)
S0 = np.ones((n, 1))
S1 = np.eye(T.max() + 1)[T]
S2 = np.eye(M.max() + 1)[M]
S3 = np.eye(Lc.max() + 1)[Lc]
Ps = [proj(S) for S in (S0, S1, S2, S3)]
Zs = [S1, S2, S3]
nss, ndf, ncoef = [], [], []
for i in range(3):
    Pi = Ps[i + 1] - Ps[i]
    d = round(np.trace(Pi))
    nss.append(yy @ Pi @ yy)
    ndf.append(d)
    ncoef.append([np.trace(Pi @ Z @ Z.T) / d for Z in Zs])
idx("NS_TOP", T)
idx("NS_MID", M)
idx("NS_LOW", Lc)
arr("NS_Y", yy)
arr("NS_SS", nss)
arr("NS_DF", ndf)
arr("NS_COEF", np.array(ncoef))
arr("NS_SSE", yy @ yy - yy @ Ps[3] @ yy)

# ---------------------------------------------------------------- mixed model, crossed random effects
ns, ni = 6, 4
S, I, Tt, xx = [], [], [], []
for s in range(ns):
    for i in range(ni):
        for r in range(int(rng.integers(1, 3))):
            S.append(s)
            I.append(i)
            Tt.append(int(rng.integers(0, 2)))
            xx.append(round(float(rng.normal(0, 1)), 3))
S = np.array(S)
I = np.array(I)
Tt = np.array(Tt)
xx = np.array(xx)
n = len(S)
ym = np.round(5 + 0.7 * xx + np.where(Tt == 0, 0.5, -0.5) + rng.normal(0, 1.1, ns)[S] + rng.normal(0, 0.6, ni)[I]
              + rng.normal(0, 0.7, n), 3)
tcode = np.where(Tt == 0, 1.0, -1.0)  # level "a" = +1, "b" = -1 (sum-to-zero)
Xm = np.column_stack([np.ones(n), xx, tcode])
Zs_ = np.eye(ns)[S]
Zi_ = np.eye(ni)[I]
p = Xm.shape[1]


def m2ll(phi, method):
    s2s, s2i, s2e = phi
    V = s2s * Zs_ @ Zs_.T + s2i * Zi_ @ Zi_.T + s2e * np.eye(n)
    Lc_ = np.linalg.cholesky(V)
    Vi_X = np.linalg.solve(V, Xm)
    XtViX = Xm.T @ Vi_X
    beta = np.linalg.solve(XtViX, Xm.T @ np.linalg.solve(V, ym))
    r = ym - Xm @ beta
    q = r @ np.linalg.solve(V, r)
    ldv = 2 * np.log(np.diag(Lc_)).sum()
    if method == "reml":
        return (n - p) * np.log(2 * np.pi) + ldv + np.linalg.slogdet(XtViX)[1] + q
    return n * np.log(2 * np.pi) + ldv + q


def fit(method):
    best = None
    for st in ([1, 1, 1], [0.1, 0.1, 1], [3, 0.5, 0.5]):
        r = optimize.minimize(lambda lp: m2ll(np.exp(lp), method), np.log(st), method="Nelder-Mead",
                              options={"xatol": 1e-10, "fatol": 1e-12, "maxiter": 20000})
        r = optimize.minimize(lambda lp: m2ll(np.exp(lp), method), r.x, method="BFGS")
        if best is None or r.fun < best.fun:
            best = r
    return np.exp(best.x), best.fun


def gls(phi):
    s2s, s2i, s2e = phi
    V = s2s * Zs_ @ Zs_.T + s2i * Zi_ @ Zi_.T + s2e * np.eye(n)
    C = np.linalg.inv(Xm.T @ np.linalg.solve(V, Xm))
    beta = C @ Xm.T @ np.linalg.solve(V, ym)
    return beta, C


phi_r, f_r = fit("reml")
beta, C = gls(phi_r)
# Satterthwaite: observed information of the REML criterion by central differences
h = 1e-3 * phi_r
H = np.zeros((3, 3))
f = lambda v: m2ll(v, "reml")
for i in range(3):
    for j in range(3):
        ei = np.zeros(3); ei[i] = h[i]
        ej = np.zeros(3); ej[j] = h[j]
        H[i, j] = (f(phi_r + ei + ej) - f(phi_r + ei - ej) - f(phi_r - ei + ej) + f(phi_r - ei - ej)) / (4 * h[i] * h[j])
covphi = 2 * np.linalg.inv(H)
sat = []
for k in range(p):
    g = np.zeros(3)
    for i in range(3):
        e = np.zeros(3); e[i] = h[i]
        g[i] = (gls(phi_r + e)[1][k, k] - gls(phi_r - e)[1][k, k]) / (2 * h[i])
    sat.append(2 * C[k, k] ** 2 / (g @ covphi @ g))
phi_m, f_m = fit("ml")
beta_m, C_m = gls(phi_m)
idx("MX_S", S)
idx("MX_I", I)
idx("MX_T", Tt)
arr("MX_X", xx)
arr("MX_Y", ym)
arr("MX_REML_PHI", phi_r)
arr("MX_REML_M2LL", [f_r])
arr("MX_REML_BETA", beta)
arr("MX_REML_SE", np.sqrt(np.diag(C)))
arr("MX_REML_DF", sat)
arr("MX_REML_SEVAR", np.sqrt(np.diag(covphi)))
arr("MX_ML_PHI", phi_m)
arr("MX_ML_M2LL", [f_m])
arr("MX_ML_BETA", beta_m)
print("".join(out))
