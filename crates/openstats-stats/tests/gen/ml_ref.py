"""Reference values for tests/ml_reference.rs, from scikit-learn (decision trees, gradient boosting).

Run: python3 ml_ref.py > ../common/ml_data.rs
The data are generated here from a fixed numpy seed and printed in full, so the Rust tests do not
depend on numpy.
"""
import numpy as np
from sklearn.tree import DecisionTreeRegressor, DecisionTreeClassifier
from sklearn.ensemble import GradientBoostingRegressor, GradientBoostingClassifier

rng = np.random.default_rng(20261117)
n = 90
x1 = np.round(rng.uniform(0, 10, n), 3)
x2 = np.round(rng.normal(5, 2, n), 3)
x3 = rng.integers(1, 6, n).astype(float)
x4 = np.round(rng.uniform(-1, 1, n), 3)
X = np.column_stack([x1, x2, x3, x4])
y = np.round(np.where(x1 < 5, 2.0, 6.0) + 0.8 * x2 + (x3 > 3) * 1.5 + rng.normal(0, 0.6, n), 4)
score = x1 - 5 + 0.7 * (x2 - 5) + rng.normal(0, 1.2, n)
cls3 = np.where(score < -1.5, 0, np.where(score < 1.5, 1, 2))
cls2 = (score > 0).astype(int)


def arr(name, a, ty="f64"):
    flat = ", ".join(repr(float(v)) if ty == "f64" else str(int(v)) for v in np.ravel(a))
    return f"pub const {name}: &[{ty}] = &[{flat}];\n"


out = ["// Generated by tests/gen/ml_ref.py (scikit-learn %s). Do not edit.\n" % __import__('sklearn').__version__]
out.append("#![allow(clippy::approx_constant, clippy::excessive_precision)]\n")
for i, c in enumerate([x1, x2, x3, x4]):
    out.append(arr(f"X{i+1}", c))
out.append(arr("Y", y))
out.append(arr("CLS3", cls3, "usize"))
out.append(arr("CLS2", cls2, "usize"))

# Regression tree: depth 4 and the full tree.
t = DecisionTreeRegressor(max_depth=4, min_samples_leaf=3, random_state=0).fit(X, y)
out.append(arr("REG_TREE_PRED", t.predict(X)))
out.append(f"pub const REG_TREE_LEAVES: usize = {t.get_n_leaves()};\n")
out.append(arr("REG_TREE_IMP", t.feature_importances_))
t = DecisionTreeRegressor(min_samples_leaf=3, random_state=0).fit(X, y)
out.append(arr("REG_FULL_PRED", t.predict(X)))
out.append(f"pub const REG_FULL_LEAVES: usize = {t.get_n_leaves()};\n")
path = t.cost_complexity_pruning_path(X, y)
out.append(arr("REG_CCP_ALPHAS", path.ccp_alphas))
leaves = []
for a in path.ccp_alphas:
    tt = DecisionTreeRegressor(min_samples_leaf=3, random_state=0, ccp_alpha=a).fit(X, y)
    leaves.append(tt.get_n_leaves())
out.append(arr("REG_CCP_LEAVES", leaves, "usize"))
out.append(f"pub const REG_ROOT_IMPURITY: f64 = {float(np.var(y))!r};\n")

# Classification trees.
for crit in ("gini", "entropy"):
    t = DecisionTreeClassifier(criterion=crit, max_depth=3, min_samples_leaf=5, random_state=0).fit(X, cls3)
    out.append(arr(f"CLS3_{crit.upper()}_PROBA", t.predict_proba(X)))
    out.append(f"pub const CLS3_{crit.upper()}_LEAVES: usize = {t.get_n_leaves()};\n")
    out.append(arr(f"CLS3_{crit.upper()}_IMP", t.feature_importances_))

# Gradient boosting.
g = GradientBoostingRegressor(n_estimators=30, learning_rate=0.1, max_depth=2, subsample=1.0,
                              criterion="squared_error", random_state=0).fit(X, y)
out.append(arr("GB_REG_PRED", g.predict(X)))
g = GradientBoostingRegressor(loss="huber", alpha=0.9, n_estimators=30, learning_rate=0.1, max_depth=2,
                              subsample=1.0, criterion="squared_error", random_state=0).fit(X, y)
out.append(arr("GB_HUBER_PRED", g.predict(X)))
g = GradientBoostingRegressor(loss="huber", alpha=0.9, n_estimators=1, learning_rate=0.1, max_depth=2,
                              subsample=1.0, random_state=0).fit(X, y)
out.append(arr("GB_HUBER1_PRED", g.predict(X)))
g = GradientBoostingClassifier(n_estimators=30, learning_rate=0.2, max_depth=2, subsample=1.0,
                               criterion="squared_error", random_state=0).fit(X, cls2)
out.append(arr("GB_BIN_PROBA", g.predict_proba(X)))
g = GradientBoostingClassifier(n_estimators=25, learning_rate=0.2, max_depth=2, subsample=1.0,
                               criterion="squared_error", random_state=0).fit(X, cls3)
out.append(arr("GB_MULTI_PROBA", g.predict_proba(X)))
print("".join(out))
