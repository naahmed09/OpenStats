"""Reference values for tests/nonparametric2.rs. Run: python3 np2_ref.py > ../common/np2_data.rs

KS two-sample: scipy.stats.ks_2samp (exact, asymptotic); Ansari: scipy.stats.ansari; Mood: scipy.stats.mood;
normal scores: NumPy brute force with scipy norm.ppf; Mann-Kendall: brute-force pair loops.
"""
import numpy as np
from scipy import stats

rng = np.random.default_rng(5517)


def arr(name, a):
    return f"pub const {name}: &[f64] = &[{', '.join(repr(float(v)) for v in np.ravel(a))}];\n"


def sc(name, v):
    return f"pub const {name}: f64 = {float(v)!r};\n"


out = "// Generated by tests/gen/np2_ref.py -- do not edit.\n"
x = np.round(rng.normal(0, 1, 17), 4)
y = np.round(rng.normal(0.6, 1.5, 23), 4)
out += arr("KS_X", x) + arr("KS_Y", y)
for alt, tag in (("two-sided", "TWO"), ("greater", "GT"), ("less", "LT")):
    r = stats.ks_2samp(x, y, alternative=alt, method="exact")
    out += sc(f"KS_{tag}_STAT", r.statistic) + sc(f"KS_{tag}_P", r.pvalue)
# larger asymptotic (ties -> asymptotic in our code, so use integers with ties)
xi = rng.integers(0, 12, 60).astype(float)
yi = rng.integers(2, 16, 70).astype(float)
r = stats.ks_2samp(xi, yi, method="asymp")
out += arr("KS_TX", xi) + arr("KS_TY", yi) + sc("KS_T_STAT", r.statistic) + sc("KS_T_P", r.pvalue)

a = np.round(rng.normal(0, 1, 12), 4)
b = np.round(rng.normal(0, 2.2, 15), 4)
out += arr("AB_X", a) + arr("AB_Y", b)
r = stats.ansari(a, b)
out += sc("AB_STAT", r.statistic) + sc("AB_P", r.pvalue)
a2 = np.round(rng.normal(0, 1, 40), 4)
b2 = np.round(rng.normal(0, 1.6, 45), 4)
out += arr("AB2_X", a2) + arr("AB2_Y", b2)
r = stats.ansari(a2, b2)
out += sc("AB2_STAT", r.statistic) + sc("AB2_P", r.pvalue)

a3 = np.round(rng.normal(0, 1, 60), 4)
b3 = np.round(rng.normal(0, 1.4, 70), 4)
out += arr("AB3_X", a3) + arr("AB3_Y", b3)
r = stats.ansari(a3, b3)
out += sc("AB3_STAT", r.statistic) + sc("AB3_P", r.pvalue)

r = stats.mood(a2, b2)
out += sc("MOOD_Z", r.statistic) + sc("MOOD_P", r.pvalue)

g = [np.round(rng.normal(m, 1, n), 3) for m, n in ((0, 9), (0.5, 11), (1.2, 8))]
allv = np.concatenate(g)
rk = stats.rankdata(allv)
sc_ = stats.norm.ppf(rk / (len(allv) + 1))
s2 = (sc_ ** 2).sum() / (len(allv) - 1)
off = 0
stat = 0.0
for gi in g:
    seg = sc_[off:off + len(gi)]
    off += len(gi)
    stat += len(gi) * seg.mean() ** 2 / s2
out += arr("NS_G1", g[0]) + arr("NS_G2", g[1]) + arr("NS_G3", g[2])
out += sc("NS_STAT", stat) + sc("NS_P", stats.chi2.sf(stat, 2))

t = np.round(np.cumsum(rng.normal(0.15, 1, 30)) + rng.integers(0, 3, 30), 1)
n = len(t)
S = sum(np.sign(t[j] - t[i]) for i in range(n) for j in range(i + 1, n))
_, cnt = np.unique(t, return_counts=True)
var = (n * (n - 1) * (2 * n + 5) - sum(c * (c - 1) * (2 * c + 5) for c in cnt)) / 18
z = (S - np.sign(S)) / np.sqrt(var)
slopes = [(t[j] - t[i]) / (j - i) for i in range(n) for j in range(i + 1, n)]
out += arr("MK_X", t) + sc("MK_S", S) + sc("MK_VAR", var) + sc("MK_Z", z)
out += sc("MK_P", 2 * stats.norm.sf(abs(z))) + sc("MK_SEN", np.median(slopes))
print(out, end="")
