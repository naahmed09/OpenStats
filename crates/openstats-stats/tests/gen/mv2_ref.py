"""Reference values for tests/mv2.rs. Run: python3 mv2_ref.py > ../common/mv2_data.rs

Correspondence analysis by NumPy SVD of the standardized residuals (chi-square checked against
scipy.stats.chi2_contingency); multiple CA by CA of the indicator matrix; promax by the textbook
least-squares-on-powered-varimax algorithm (as in R's stats::promax) in NumPy.
"""
import numpy as np
from scipy import stats

rng = np.random.default_rng(2024)


def arr(name, a):
    return f"pub const {name}: &[f64] = &[{', '.join(repr(float(v)) for v in np.ravel(a))}];\n"


def sc(name, v):
    return f"pub const {name}: f64 = {float(v)!r};\n"


def ca(N):
    n = N.sum()
    P = N / n
    r, c = P.sum(1), P.sum(0)
    S = (P - np.outer(r, c)) / np.sqrt(np.outer(r, c))
    U, s, Vt = np.linalg.svd(S, full_matrices=False)
    k = min(N.shape) - 1
    F = (U[:, :k] * s[:k]) / np.sqrt(r)[:, None]
    G = (Vt.T[:, :k] * s[:k]) / np.sqrt(c)[:, None]
    return s[:k], F, G, (S ** 2).sum(), r, c, S


def sign_fix(F, G):
    # make the first row coordinate of each axis positive so comparisons are sign independent
    sg = np.sign(F[0, :])
    sg[sg == 0] = 1
    return F * sg, G * sg


out = "// Generated by tests/gen/mv2_ref.py -- do not edit.\n"
N = np.array([[20, 5, 12, 7], [4, 25, 9, 3], [10, 8, 30, 6], [2, 11, 5, 22], [9, 4, 6, 8]], float)
s, F, G, tin, r, c, S = ca(N)
F, G = sign_fix(F, G)
out += arr("CA_TABLE", N) + arr("CA_SV", s) + arr("CA_ROW", F) + arr("CA_COL", G) + sc("CA_TOTAL_INERTIA", tin)
chi = stats.chi2_contingency(N, correction=False)[0]
assert abs(chi - N.sum() * tin) < 1e-9
out += sc("CA_CHI2", chi)
ctr = (r[:, None] * F ** 2) / (s ** 2)
d2 = (S ** 2).sum(1) / r
out += arr("CA_ROW_CTR", ctr) + arr("CA_ROW_COS", F ** 2 / d2[:, None]) + arr("CA_ROW_MASS", r)

# MCA: 3 variables, 60 observations
levels = [["a", "b", "c"], ["x", "y"], ["p", "q", "r", "s"]]
cols = [rng.choice(l, 60) for l in levels]
cols[1] = np.where(cols[0] == "a", "x", cols[1])  # association
ind = []
labels = []
for k, col in enumerate(cols):
    for l in sorted(set(col)):
        ind.append((col == l).astype(float))
        labels.append(f"v{k}={l}")
Z = np.array(ind).T
s2, F2, G2, tin2, *_ = ca(Z)
kk = Z.shape[1] - len(cols)
F2, G2 = sign_fix(F2[:, :kk], G2[:, :kk])
out += "pub const MCA_V0: &[&str] = &[" + ", ".join(f'"{x}"' for x in cols[0]) + "];\n"
out += "pub const MCA_V1: &[&str] = &[" + ", ".join(f'"{x}"' for x in cols[1]) + "];\n"
out += "pub const MCA_V2: &[&str] = &[" + ", ".join(f'"{x}"' for x in cols[2]) + "];\n"
out += arr("MCA_SV", s2[:kk]) + arr("MCA_COL", G2) + sc("MCA_TOTAL_INERTIA", tin2) + sc("MCA_NCOL", Z.shape[1])

# promax
p, m = 8, 3
A = rng.normal(0, 1, (p, m))
Q, _ = np.linalg.qr(rng.normal(0, 1, (m, m)))
V = A @ Q
power = 4.0
Qp = V * np.abs(V) ** (power - 1)
U = np.linalg.solve(V.T @ V, V.T @ Qp)
d = np.diag(np.linalg.inv(U.T @ U))
U = U * np.sqrt(d)
T = Q @ U
pattern = A @ T
phi = np.linalg.inv(T.T @ T)
out += arr("PM_A", A) + arr("PM_Q", Q) + arr("PM_PATTERN", pattern) + arr("PM_PHI", phi) + arr("PM_STRUCT", pattern @ phi)
print(out, end="")
