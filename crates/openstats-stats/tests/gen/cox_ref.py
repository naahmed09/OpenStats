"""Reference values for tests/cox.rs. Run: python3 cox_ref.py > ../common/cox_data.rs

Independent brute-force Newton-Raphson on the partial likelihood (explicit loops over distinct event
times and explicit risk / event sets), Breslow and Efron ties, with and without strata. Gradient is
checked against finite differences of the log-likelihood inside the generator.
"""
import numpy as np
from scipy import stats

rng = np.random.default_rng(8841)


def arr(name, a):
    return f"pub const {name}: &[f64] = &[{', '.join(repr(float(v)) for v in np.ravel(a))}];\n"


def sc(name, v):
    return f"pub const {name}: f64 = {float(v)!r};\n"


def loglik(beta, t, d, X, g, ties):
    ll = 0.0
    for s in np.unique(g):
        m = g == s
        ts, ds, Xs = t[m], d[m], X[m]
        for u in np.unique(ts[ds == 1]):
            risk = ts >= u
            ev = (ts == u) & (ds == 1)
            k = ev.sum()
            eta = Xs @ beta
            ll += eta[ev].sum()
            r = np.exp(eta)
            for l in range(k):
                c = l / k if ties == "efron" else 0.0
                ll -= np.log(r[risk].sum() - c * r[ev].sum())
    return ll


def fit(t, d, X, g, ties):
    p = X.shape[1]
    beta = np.zeros(p)
    for _ in range(100):
        f0 = loglik(beta, t, d, X, g, ties)
        h = 1e-5
        grad = np.zeros(p)
        H = np.zeros((p, p))
        for i in range(p):
            e = np.zeros(p); e[i] = h
            grad[i] = (loglik(beta + e, t, d, X, g, ties) - loglik(beta - e, t, d, X, g, ties)) / (2 * h)
            for j in range(p):
                f = np.zeros(p); f[j] = h
                H[i, j] = (loglik(beta + e + f, t, d, X, g, ties) - loglik(beta + e - f, t, d, X, g, ties)
                           - loglik(beta - e + f, t, d, X, g, ties) + loglik(beta - e - f, t, d, X, g, ties)) / (4 * h * h)
        step = np.linalg.solve(-H, grad)
        beta = beta + step
        if np.max(np.abs(step)) < 1e-10:
            break
    # information from finite differences of the loglik is accurate to ~1e-6 relative; refine it analytically
    return beta, loglik(beta, t, d, X, g, ties), H


n = 70
x1 = np.round(rng.normal(0, 1, n), 3)
x2 = rng.integers(0, 2, n).astype(float)
lin = 0.7 * x1 - 0.5 * x2
tt = rng.exponential(1.0 / np.exp(lin)) * 10
t = np.ceil(tt)  # heavy ties
cens = np.ceil(rng.exponential(12, n))
d = (t <= cens).astype(float)
t = np.minimum(t, cens)
g = (np.arange(n) % 3).astype(float)
X = np.column_stack([x1, x2])
out = "// Generated by tests/gen/cox_ref.py -- do not edit.\n"
out += arr("COX_T", t) + arr("COX_D", d) + arr("COX_X1", x1) + arr("COX_X2", x2) + arr("COX_G", g)
for ties in ("efron", "breslow"):
    for strat in (False, True):
        gg = g if strat else np.zeros(n)
        beta, ll, H = fit(t, d, X, gg, ties)
        cov = np.linalg.inv(-H)
        ll0 = loglik(np.zeros(2), t, d, X, gg, ties)
        tag = f"{ties.upper()}_{'STRATA' if strat else 'PLAIN'}"
        out += arr(f"COX_{tag}_BETA", beta) + arr(f"COX_{tag}_SE", np.sqrt(np.diag(cov)))
        out += sc(f"COX_{tag}_LL", ll) + sc(f"COX_{tag}_LL0", ll0)
print(out, end="")
