"""Reference for tests/ml2.rs (Phase 5i): independent NumPy/SciPy code.

1. Logistic coefficients on a fixed MARS basis: Newton-Raphson in NumPy, cross-checked against
   scipy.optimize.minimize (BFGS) on the negative log-likelihood.
2. Partial dependence / ICE of an explicit MARS model (identity and logit link) by brute force.
Run: python3 ml2_ref.py > ../common/ml2_data.rs
"""
import numpy as np
from scipy.optimize import minimize

out = []


def arr(name, a):
    out.append(f"pub const {name}: &[f64] = &[{', '.join(repr(float(v)) for v in np.ravel(a))}];\n")


def sc(name, v):
    out.append(f"pub const {name}: f64 = {float(v)!r};\n")


def hinge(f, X):
    v, k, s = f
    x = X[:, v]
    return np.maximum(0, x - k) if s == 1 else np.maximum(0, k - x) if s == -1 else x


def basis(terms, X):
    cols = []
    for t in terms:
        c = np.ones(len(X))
        for f in t:
            c = c * hinge(f, X)
        cols.append(c)
    return np.column_stack(cols)


def sigmoid(e):
    return 1 / (1 + np.exp(-e))


# ---------------------------------------------------------------- 1. logistic on a basis
rng = np.random.default_rng(20261118)
N = 150
X = rng.uniform(-1, 1, size=(N, 3))
TERMS = [[], [(0, 0.2, 1)], [(1, 0.1, -1)], [(0, 0.0, 0), (2, 0.0, 1)]]
B = basis(TERMS, X)
eta = B @ np.array([-0.3, 2.5, -2.0, 1.2])
y = (rng.uniform(size=N) < sigmoid(eta)).astype(float)


def nll(b):
    e = B @ b
    return np.sum(np.logaddexp(0, e) - y * e)


b = np.zeros(4)
for _ in range(100):
    mu = sigmoid(B @ b)
    W = mu * (1 - mu)
    g = B.T @ (y - mu)
    H = B.T @ (B * W[:, None])
    step = np.linalg.solve(H, g)
    b = b + step
    if np.max(np.abs(step)) < 1e-14:
        break
res = minimize(nll, np.zeros(4), method="BFGS", options={"gtol": 1e-10})
assert np.allclose(res.x, b, atol=1e-5), (res.x, b)
mu = sigmoid(B @ b)
W = mu * (1 - mu)
cov = np.linalg.inv(B.T @ (B * W[:, None]))
se = np.sqrt(np.diag(cov))
dev = 2 * nll(b)
p1 = y.mean()
null_dev = -2 * (y.sum() * np.log(p1) + (N - y.sum()) * np.log(1 - p1))
arr("LG_X", X.T)  # column-major: x1 then x2 then x3
arr("LG_Y", y)
arr("LG_COEF", b)
arr("LG_SE", se)
arr("LG_PROB", mu)
sc("LG_DEV", dev)
sc("LG_NULL_DEV", null_dev)

# ---------------------------------------------------------------- 2. partial dependence
M = 60
x1 = rng.uniform(-1, 1, M)
x2 = rng.uniform(-1, 1, M)
cat = rng.integers(0, 3, M)  # a, b, c
Xe = np.column_stack([x1, x2, (cat == 1).astype(float), (cat == 2).astype(float)])
PT = [[], [(0, 0.1, 1)], [(1, 0.3, -1)], [(2, 0.0, 0)], [(3, 0.0, 0)], [(0, 0.1, 1), (1, -0.2, 1)]]
COEF = np.array([0.5, 0.8, -0.5, 0.7, -0.4, 0.6])
BE = basis(PT, Xe)
eta_pd = BE @ COEF


def f_identity(Xrows):
    return basis(PT, Xrows) @ COEF


def pd_numeric(col, grid, link):
    avg, ice = [], []
    for g in grid:
        Z = Xe.copy()
        Z[:, col] = g
        e = f_identity(Z)
        p = sigmoid(e) if link else e
        avg.append(p.mean())
        ice.append(p)
    return np.array(avg), np.array(ice)  # ice[g][row]


G1 = np.linspace(np.quantile(x1, 0.1), np.quantile(x1, 0.9), 7)
for link, tag in [(False, "ID"), (True, "LO")]:
    avg, ice = pd_numeric(0, G1, link)
    arr(f"PD_{tag}_X1_GRID", G1)
    arr(f"PD_{tag}_X1_AVG", avg)
    arr(f"PD_{tag}_X1_ICE", ice.T)  # row-major by observation: ice[row][grid]

# categorical predictor (3 levels), identity link
cat_avg = []
for lvl in range(3):
    Z = Xe.copy()
    Z[:, 2] = float(lvl == 1)
    Z[:, 3] = float(lvl == 2)
    cat_avg.append(f_identity(Z).mean())
arr("PD_CAT_AVG", cat_avg)

# two-way: x1 (6 points) by x2 (5 points), identity link
GA = np.linspace(np.quantile(x1, 0.1), np.quantile(x1, 0.9), 6)
GB = np.linspace(np.quantile(x2, 0.1), np.quantile(x2, 0.9), 5)
Z2 = np.zeros((5, 6))
for j, b2 in enumerate(GB):
    for i, a in enumerate(GA):
        Z = Xe.copy()
        Z[:, 0] = a
        Z[:, 1] = b2
        Z2[j, i] = f_identity(Z).mean()
arr("PD_2D_X", GA)
arr("PD_2D_Y", GB)
arr("PD_2D_Z", Z2)

arr("PD_X1", x1)
arr("PD_X2", x2)
arr("PD_CAT", cat.astype(float))
print("// Generated by tests/gen/ml2_ref.py (NumPy/SciPy). Do not edit.")
print("#![allow(dead_code)]")
print("".join(out))
