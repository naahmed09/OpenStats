"""Reference values for tests/reliability2.rs. Run: python3 rel2_ref.py > ../common/rel2_data.rs

MCF / Crow-AMSAA: explicit loops and scipy chi2; demonstration plans: scipy binom brute force / brentq;
gamma, threshold Weibull, Eyring: direct scipy.optimize maximum likelihood; Turnbull: independent NumPy EM.
"""
import numpy as np
from scipy import stats, optimize

rng = np.random.default_rng(20261118)


def arr(name, a):
    return f"pub const {name}: &[f64] = &[{', '.join(repr(float(v)) for v in np.ravel(a))}];\n"


def sc(name, v):
    return f"pub const {name}: f64 = {float(v)!r};\n"


def it(name, v):
    return f"pub const {name}: u64 = {int(v)};\n"


out = "// Generated by tests/gen/rel2_ref.py -- do not edit.\n"

# ---- repairable systems: 5 systems, power-law-ish event times
ends = np.array([120.0, 150.0, 100.0, 140.0, 90.0])
systems = []
for e in ends:
    n = rng.poisson(6)
    t = np.sort(np.round(e * rng.random(n) ** 1.6, 1))
    t = t[t > 0]
    systems.append(t)
sid, tim = [], []
for i, t in enumerate(systems):
    for x in t:
        sid.append(i)
        tim.append(x)
out += arr("SYS_ID", sid) + arr("SYS_TIME", tim) + arr("SYS_END", ends)

# MCF Nelson + Lawless-Nadeau
alltimes = np.unique(np.concatenate(systems))
mcf = 0.0
acc = np.zeros(len(systems))
mc, mv = [], []
for t in alltimes:
    r = sum(1 for e in ends if e >= t)
    dn = np.array([np.sum(s == t) for s in systems], float)
    d = dn.sum()
    mcf += d / r
    for i in range(len(systems)):
        if ends[i] >= t:
            acc[i] += (dn[i] - d / r) / r
    mc.append(mcf)
    mv.append(np.sqrt(np.sum(acc**2)))
out += arr("MCF_T", alltimes) + arr("MCF_EST", mc) + arr("MCF_SE", mv)

# Crow-AMSAA pooled, time truncated
N = sum(len(s) for s in systems)
sl = sum(np.sum(np.log(e / s)) for s, e in zip(systems, ends))
beta = N / sl
lam = N / np.sum(ends**beta)
c = stats.chi2(2 * N)
out += sc("CROW_BETA", beta) + sc("CROW_LAMBDA", lam)
out += sc("CROW_BLO", beta * c.ppf(0.025) / (2 * N)) + sc("CROW_BHI", beta * c.ppf(0.975) / (2 * N))
chi = 2 * N / beta
pl = c.cdf(chi)
out += sc("CROW_CHI", chi) + sc("CROW_CHIP", min(1.0, 2 * min(pl, 1 - pl)))
st = sum(np.sum(s) for s in systems)
mp = sum(len(s) * e / 2 for s, e in zip(systems, ends))
vp = sum(len(s) * e * e / 12 for s, e in zip(systems, ends))
u = (st - mp) / np.sqrt(vp)
out += sc("CROW_U", u) + sc("CROW_UP", 2 * stats.norm.sf(abs(u)))

# ---- demonstration plans
def plan_n(shape, t, R, C, c, T, nmax=100000):
    p = 1 - R ** ((T / t) ** shape)
    for n in range(c + 1, nmax):
        if stats.binom.cdf(c, n, p) <= 1 - C:
            return n
cases = [(1.0, 100.0, 0.9, 0.9, 0, 100.0), (2.0, 500.0, 0.95, 0.9, 1, 400.0), (1.5, 1000.0, 0.8, 0.95, 2, 1500.0)]
out += "pub const DEMO_N: &[(f64, f64, f64, f64, u64, f64, u64)] = &[\n"
for (sh, t, R, C, c, T) in cases:
    out += f"    ({sh!r}, {t!r}, {R!r}, {C!r}, {c}, {float(T)!r}, {plan_n(sh, t, R, C, c, T)}),\n"
out += "];\n"
tcases = [(2.0, 500.0, 0.95, 0.9, 1, 40), (1.0, 100.0, 0.9, 0.9, 0, 30)]
out += "pub const DEMO_T: &[(f64, f64, f64, f64, u64, u64, f64)] = &[\n"
for (sh, t, R, C, c, n) in tcases:
    ps = optimize.brentq(lambda p: stats.binom.cdf(c, n, p) - (1 - C), 1e-12, 1 - 1e-12, xtol=1e-14)
    T = t * (np.log(1 - ps) / np.log(R)) ** (1 / sh)
    out += f"    ({sh!r}, {t!r}, {R!r}, {C!r}, {c}, {n}, {float(T)!r}),\n"
out += "];\n"

# ---- gamma MLE with right censoring
g = stats.gamma.rvs(2.5, scale=40.0, size=60, random_state=11)
cens = rng.random(60) < 0.25
tt = np.where(cens, g * 0.7, g)
tt = np.round(tt, 2)
out += arr("GAM_T", tt) + arr("GAM_C", cens.astype(float))
def nll(x):
    a, th = np.exp(x)
    return -(np.sum(stats.gamma.logpdf(tt[~cens], a, scale=th)) + np.sum(stats.gamma.logsf(tt[cens], a, scale=th)))
r = optimize.minimize(nll, [np.log(2.0), np.log(30.0)], method="Nelder-Mead", options={"xatol": 1e-10, "fatol": 1e-12, "maxiter": 5000})
out += sc("GAM_SHAPE", np.exp(r.x[0])) + sc("GAM_SCALE", np.exp(r.x[1])) + sc("GAM_LL", -r.fun)

# ---- threshold Weibull (exact data): profile over gamma
w = 120.0 + stats.weibull_min.rvs(1.8, scale=60.0, size=50, random_state=5)
w = np.round(w, 2)
out += arr("THR_T", w)
def wll(par, x):
    k, s = np.exp(par)
    return -np.sum(stats.weibull_min.logpdf(x, k, scale=s))
def prof(gm):
    x = w - gm
    rr = optimize.minimize(wll, [0.5, np.log(np.mean(x))], args=(x,), method="Nelder-Mead", options={"xatol": 1e-10, "fatol": 1e-13, "maxiter": 5000})
    return rr.fun
gb = optimize.minimize_scalar(prof, bounds=(w.min() - 200, w.min() - 1e-3 * (w.max() - w.min())), method="bounded", options={"xatol": 1e-8})
out += sc("THR_GAMMA", gb.x) + sc("THR_LL", -gb.fun)

# ---- Turnbull: independent EM on interval data (unique quantity = log-likelihood)
L = np.round(rng.random(25) * 30, 1)
R = np.round(L + rng.random(25) * 15 + 0.5, 1)
R[3] = np.inf
L[5] = 0.0
out += arr("TB_L", L) + arr("TB_R", np.where(np.isinf(R), -1.0, R))
pts = sorted(set(L) | set(R[np.isfinite(R)]))
cand = sorted(set(list(L) + [x for x in R if np.isfinite(x)]))
# candidate support points: every endpoint (mass at a point); likelihood-equivalent to innermost intervals
def covers(i, p):
    return (p > L[i] if L[i] > 0 else p > 0) and p <= R[i]
sup = [p for p in cand if p > 0]
A = np.array([[1.0 if covers(i, p) else 0.0 for p in sup] for i in range(25)])
m = np.ones(len(sup)) / len(sup)
for _ in range(200000):
    d = A @ m
    mn = (A * m / d[:, None]).sum(0) / 25
    if np.max(np.abs(mn - m)) < 1e-14:
        m = mn
        break
    m = mn
out += sc("TB_LL", np.sum(np.log(A @ m)))

# ---- Eyring, lognormal, exact data
temp = np.repeat([40.0, 60.0, 80.0], 12)
a0, b0, sg = -4.0, 5200.0, 0.4
TK = temp + 273.16
lnt = a0 - np.log(TK) + b0 / TK + sg * rng.standard_normal(36)
et = np.round(np.exp(lnt), 2)
out += arr("EY_T", et) + arr("EY_TEMP", temp)
def ell(par):
    a, b, ls = par
    s = np.exp(ls)
    mu = a - np.log(TK) + b / TK
    z = (np.log(et) - mu) / s
    return -np.sum(stats.norm.logpdf(z) - np.log(s) - np.log(et))
re = optimize.minimize(ell, [a0, b0, np.log(0.5)], method="Nelder-Mead", options={"xatol": 1e-10, "fatol": 1e-13, "maxiter": 20000})
re = optimize.minimize(ell, re.x, method="BFGS")
out += sc("EY_A", re.x[0]) + sc("EY_B", re.x[1]) + sc("EY_SIGMA", np.exp(re.x[2])) + sc("EY_LL", -re.fun)
print(out)
