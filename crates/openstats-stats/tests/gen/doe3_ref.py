"""Reference values for tests/doe3.rs (analysis of variability). Run: python3 doe3_ref.py > ../common/doe3_data.rs

ln(s) of each replicated factor combination regressed on coded effects with numpy lstsq; p-values from scipy.
"""
import itertools
import numpy as np
from scipy import stats

rng = np.random.default_rng(5551212)


def arr(name, a):
    return f"pub const {name}: &[f64] = &[{', '.join(repr(float(v)) for v in np.ravel(a))}];\n"


out = "// Generated by tests/gen/doe3_ref.py -- do not edit.\n"
corners = list(itertools.product([-1.0, 1.0], repeat=3))
rows, y = [], []
for c in corners:
    sd = np.exp(0.2 + 0.5 * c[0] - 0.3 * c[2])
    for _ in range(3):
        rows.append(c)
        y.append(5 + c[1] + rng.normal(0, sd))
rows = np.array(rows)
y = np.array(y)
out += arr("VAR_X", rows) + arr("VAR_Y", y)
lns = []
G = []
for c in corners:
    m = np.all(rows == c, axis=1)
    lns.append(np.log(np.std(y[m], ddof=1)))
    G.append(c)
G = np.array(G)
lns = np.array(lns)


def fit(X, tag):
    b, *_ = np.linalg.lstsq(X, lns, rcond=None)
    r = lns - X @ b
    df = len(lns) - X.shape[1]
    s2 = r @ r / df
    cov = s2 * np.linalg.inv(X.T @ X)
    se = np.sqrt(np.diag(cov))
    t = b / se
    p = 2 * stats.t.sf(np.abs(t), df)
    r2 = 1 - (r @ r) / ((lns - lns.mean()) @ (lns - lns.mean()))
    return arr(f"VAR_{tag}_COEF", b) + arr(f"VAR_{tag}_SE", se) + arr(f"VAR_{tag}_P", p) + f"pub const VAR_{tag}_R2: f64 = {float(r2)!r};\n"


X1 = np.column_stack([np.ones(8), G])
out += fit(X1, "MAIN")
X2 = np.column_stack([np.ones(8), G, G[:, 0] * G[:, 1], G[:, 0] * G[:, 2], G[:, 1] * G[:, 2]])
out += fit(X2, "INT")
print(out)
