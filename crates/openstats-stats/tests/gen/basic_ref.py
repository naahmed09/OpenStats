"""Reference values for the Phase 5a goodness-of-fit test: python3 basic_ref.py > ../common/basic_data.rs"""
import numpy as np
from scipy import stats

cases = {"EQ": ([18, 25, 31, 26], None), "PR": ([44, 31, 17, 8], [0.5, 0.3, 0.15, 0.05]), "CT": ([12, 30, 41], [10, 30, 50])}
print("// Generated by tests/gen/basic_ref.py (SciPy chisquare).\n")
for k, (o, e) in cases.items():
    o = np.array(o, float)
    exp = np.full(len(o), o.sum() / len(o)) if e is None else np.array(e, float) / np.sum(e) * o.sum()
    st, p = stats.chisquare(o, exp)
    print(f"pub const GOF_{k}_OBS: &[f64] = &{[float(x) for x in o]!r};")
    print(f"pub const GOF_{k}_EXP: &[f64] = &{[float(x) for x in exp]!r};")
    print(f"pub const GOF_{k}_STAT: f64 = {float(st)!r};")
    print(f"pub const GOF_{k}_P: f64 = {float(p)!r};")
