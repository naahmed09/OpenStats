"""Reference values for tests/doe2.rs. Run: python3 doe2_ref.py > ../common/doe2_data.rs

Scheffe fits: numpy lstsq; optimal designs: exhaustive search over every multiset of candidate points;
extreme vertices: scipy HalfspaceIntersection.
"""
import itertools
import numpy as np
from scipy import stats
from scipy.spatial import HalfspaceIntersection

rng = np.random.default_rng(20261118)


def arr(name, a):
    return f"pub const {name}: &[f64] = &[{', '.join(repr(float(v)) for v in np.ravel(a))}];\n"


def sc(name, v):
    return f"pub const {name}: f64 = {float(v)!r};\n"


out = "// Generated by tests/gen/doe2_ref.py -- do not edit.\n"

# ---- Scheffe special cubic on a 3-component centroid design with replicates
pts = []
for mask in range(1, 8):
    k = bin(mask).count("1")
    pts.append([1.0 / k if mask >> i & 1 else 0.0 for i in range(3)])
pts = np.array(pts + pts[:4] + [[1 / 3, 1 / 3, 1 / 3]])  # 7 + 4 + 1 = 12 runs
y = 12 * pts[:, 0] + 18 * pts[:, 1] + 25 * pts[:, 2] + 14 * pts[:, 0] * pts[:, 1] - 9 * pts[:, 1] * pts[:, 2] + 40 * pts[:, 0] * pts[:, 1] * pts[:, 2] + rng.normal(0, 0.4, len(pts))
out += arr("MIX_X", pts) + arr("MIX_Y", y)


def fit(cols):
    X = np.column_stack(cols)
    b, *_ = np.linalg.lstsq(X, y, rcond=None)
    r = y - X @ b
    sse = r @ r
    return X, b, sse


x1, x2, x3 = pts.T
lin = [x1, x2, x3]
quad = lin + [x1 * x2, x1 * x3, x2 * x3]
sc3 = quad + [x1 * x2 * x3]
n = len(y)
sst = np.sum((y - y.mean()) ** 2)
X, b, sse = fit(sc3)
p = X.shape[1]
cov = sse / (n - p) * np.linalg.inv(X.T @ X)
out += arr("MIX_COEF", b) + arr("MIX_SE", np.sqrt(np.diag(cov)))
out += sc("MIX_SSE", sse) + sc("MIX_SST", sst) + sc("MIX_R2", 1 - sse / sst) + sc("MIX_R2ADJ", 1 - (sse / (n - p)) / (sst / (n - 1)))
_, _, sse_l = fit(lin)
_, _, sse_q = fit(quad)
out += sc("MIX_SS_LIN", sst - sse_l) + sc("MIX_SS_QUAD", sse_l - sse_q) + sc("MIX_SS_CUBIC", sse_q - sse)
out += sc("MIX_P_REG", stats.f.sf(((sst - sse) / (p - 1)) / (sse / (n - p)), p - 1, n - p))

# ---- exhaustive optimal designs, 2 factors, 3 levels, quadratic model
grid = [(a, b) for a in (-1.0, 0.0, 1.0) for b in (-1.0, 0.0, 1.0)]


def frow(c):
    a, b = c
    return [1, a, b, a * b, a * a, b * b]


F = np.array([frow(c) for c in grid])
B = F.T @ F / len(grid)
for nrun in (7, 9):
    bestd, besti = -np.inf, np.inf
    for combo in itertools.combinations_with_replacement(range(9), nrun):
        X = F[list(combo)]
        M = X.T @ X
        sign, ld = np.linalg.slogdet(M)
        if sign <= 0 or np.linalg.matrix_rank(X) < 6 or np.linalg.cond(M) > 1e8:
            continue
        bestd = max(bestd, ld)
        Ainv = np.linalg.inv(M)
        besti = min(besti, np.trace(Ainv @ B))
    out += sc(f"OPT{nrun}_LOGDET", bestd) + sc(f"OPT{nrun}_IAVG", besti)

# ---- extreme vertices (4 components) via halfspace intersection
lo = np.array([0.05, 0.10, 0.0, 0.15])
hi = np.array([0.45, 0.50, 0.40, 0.55])
hs = []
for i in range(3):
    e = np.zeros(3)
    e[i] = 1.0
    hs.append(np.append(-e, lo[i]))   # -x_i + lo <= 0
    hs.append(np.append(e, -hi[i]))   # x_i - hi <= 0
e = np.ones(3)
hs.append(np.append(e, -(1 - lo[3])))   # x4 = 1 - sum >= lo4  -> sum <= 1 - lo4
hs.append(np.append(-e, (1 - hi[3])))   # x4 <= hi4 -> sum >= 1 - hi4
hs = np.array(hs)
# interior point: a feasible blend strictly inside
feas = np.array([0.2, 0.25, 0.15])
assert np.all(hs[:, :3] @ feas + hs[:, 3] < 0)
V = HalfspaceIntersection(hs, feas).intersections
V = np.unique(np.round(V, 9), axis=0)
full = np.column_stack([V, 1 - V.sum(1)])
full = full[np.lexsort(full.T[::-1])]
out += arr("EV_LO", lo) + arr("EV_HI", hi) + arr("EV_VERTS", full) + f"pub const EV_N: usize = {len(full)};\n"
print(out)
