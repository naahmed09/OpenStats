# Probit link via scipy
def nll_probit(bb):
    e = X @ bb
    return -np.sum(y * stats.norm.logcdf(e) + (1 - y) * stats.norm.logsf(e))
r = optimize.minimize(nll_probit, np.zeros(5), method="BFGS", options={"gtol": 1e-10})
arr("LG_PROBIT_COEF", r.x); sc("LG_PROBIT_DEV", 2 * r.fun)
# cloglog
