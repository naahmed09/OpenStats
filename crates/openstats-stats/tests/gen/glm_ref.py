sc("LG_AIC", -2 * ll + 2 * 5); sc("LG_BIC", -2 * ll + 5 * np.log(n))
arr("LG_FIT", mu)
h = W * np.einsum("ij,jk,ik->i", X, cov, X)
arr("LG_HAT", h)
pear = (y - mu) / np.sqrt(mu * (1 - mu))
dres = np.sign(y - mu) * np.sqrt(-2 * (y * np.log(mu) + (1 - y) * np.log(1 - mu)))
arr("LG_PEARSON", pear); arr("LG_DEVRES", dres)
sc("LG_PEARSON_CHI2", np.sum(pear ** 2))
sc("LG_AUC", roc_auc_score(y, mu))
cls = mu >= 0.5
sc("LG_TP", np.sum((y == 1) & cls)); sc("LG_FN", np.sum((y == 1) & ~cls))
sc("LG_FP", np.sum((y == 0) & cls)); sc("LG_TN", np.sum((y == 0) & ~cls))


def hl(y, mu, G=10):
    order = np.argsort(mu, kind="stable")
    ys, ms = y[order], mu[order]
    nn = len(ys)
    groups = []
    cur = [0.0, 0.0, 0.0]
    cum = 0
    for i in range(nn):
        cur[0] += 1; cur[1] += ys[i]; cur[2] += ms[i]; cum += 1
        target = nn * (len(groups) + 1) / G
        last = i == nn - 1
        tie = (not last) and ms[i + 1] == ms[i]
        if last or (cum >= target - 1e-9 and not tie and len(groups) + 1 < G):
            groups.append(cur); cur = [0.0, 0.0, 0.0]
    chi = sum((o - e) ** 2 / (m * (e / m) * (1 - e / m)) for m, o, e in groups)
    return chi, len(groups) - 2, stats.chi2.sf(chi, len(groups) - 2)


chi, dfh, ph = hl(y, mu)
sc("LG_HL_CHI", chi); sc("LG_HL_DF", dfh); sc("LG_HL_P", ph)
