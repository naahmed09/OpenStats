# ------------------------------------------------------------------ ordinal logistic
n = 200
o1 = np.round(rng.normal(0, 1, n), 3)
og = rng.integers(0, 2, n)
lat = 0.9 * o1 + 0.7 * og + rng.logistic(size=n)
cat = np.digitize(lat, [-1.0, 0.4, 1.6])  # 4 categories
arr("OR_X1", o1); arr("OR_G", og); arr("OR_CAT", cat)
Xo = np.column_stack([o1, og]).astype(float)
K = 4


def ord_ll(par):
    th = np.cumsum(np.r_[par[0], np.exp(par[1:K - 1])])
    be_ = par[K - 1:]
    e = Xo @ be_
    cum = np.column_stack([np.zeros(n)] + [special.expit(th[j] - e) for j in range(K - 1)] + [np.ones(n)])
    pr_ = cum[np.arange(n), cat + 1] - cum[np.arange(n), cat]
    return -np.sum(np.log(pr_))


def ord_ll_theta(par):
    th, be_ = par[:K - 1], par[K - 1:]
    e = Xo @ be_
    cum = np.column_stack([np.zeros(n)] + [special.expit(th[j] - e) for j in range(K - 1)] + [np.ones(n)])
    pr_ = cum[np.arange(n), cat + 1] - cum[np.arange(n), cat]
    return -np.sum(np.log(pr_))


r = optimize.minimize(ord_ll, np.r_[-1.0, np.log([1.0, 1.0]), 0, 0], method="BFGS", options={"gtol": 1e-11})
par = r.x
th = np.cumsum(np.r_[par[0], np.exp(par[1:K - 1])])
est = np.r_[th, par[K - 1:]]
r2_ = optimize.minimize(ord_ll_theta, est, method="BFGS", options={"gtol": 1e-12})
est = r2_.x


def num_hess(f, x, h=1e-4):
    k = len(x)
    H = np.zeros((k, k))
    for i in range(k):
        for j in range(k):
            xpp = x.copy(); xpm = x.copy(); xmp = x.copy(); xmm = x.copy()
            xpp[i] += h; xpp[j] += h
            xpm[i] += h; xpm[j] -= h
            xmp[i] -= h; xmp[j] += h
            xmm[i] -= h; xmm[j] -= h
            H[i, j] = (f(xpp) - f(xpm) - f(xmp) + f(xmm)) / (4 * h * h)
    return H


Hs = num_hess(ord_ll_theta, est)
