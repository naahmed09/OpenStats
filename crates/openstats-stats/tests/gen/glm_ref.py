"""Reference values for tests/glm_reference.rs (scikit-learn, SciPy, NumPy).

Run: python3 glm_ref.py > ../common/glm_data.rs
Every model is fitted here with an independent implementation:
  * logistic / Poisson coefficients: scikit-learn (no penalty); SE, deviance, AIC from NumPy
  * negative binomial, gamma, ordinal: scipy.optimize on the log-likelihood
  * nominal: scikit-learn multinomial logistic regression (baseline re-parameterised)
  * nonlinear: scipy.optimize.curve_fit
  * PLS: sklearn.cross_decomposition.PLSRegression and a leave-one-out loop
  * orthogonal regression: scipy.odr
  * weighted regression: NumPy normal equations
"""
