sc("EV_LL", lle)

# ------------------------------------------------------------------ Poisson
n = 100
p1 = np.round(rng.uniform(0, 3, n), 3)
p2 = np.round(rng.normal(0, 1, n), 3)
mu_true = np.exp(0.3 + 0.5 * p1 - 0.4 * p2)
