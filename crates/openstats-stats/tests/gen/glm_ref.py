arr("PO_FIT", mp)

# ------------------------------------------------------------------ negative binomial
th_true = 2.5
mu_nb = np.exp(0.2 + 0.6 * p1 - 0.3 * p2)
nb = rng.negative_binomial(th_true, th_true / (th_true + mu_nb)).astype(float)
