    pl = PLSRegression(n_components=3, scale=scale, tol=1e-14, max_iter=100000).fit(Xs, Y)
    pred = pl.predict(Xs)
    arr(f"PLS_{tag}_FIT", pred)
    coef = np.atleast_2d(pl.coef_)
    if coef.shape[0] != Y.shape[1]:
        coef = coef.T
    arr(f"PLS_{tag}_COEF", coef.T)  # p x q row-major
    arr(f"PLS_{tag}_ICPT", Y.mean(0) - Xs.mean(0) @ coef.T)  # constants in original units
    # sum of squares of scores per component (sign-free)
    arr(f"PLS_{tag}_TT", (pl.x_scores_ ** 2).sum(0))
    # LOO PRESS for 1..3 components
    press = np.zeros((3, Y.shape[1]))
    for i in range(n):
        tr = np.arange(n) != i
        for c in range(1, 4):
            m_ = PLSRegression(n_components=c, scale=scale, tol=1e-14, max_iter=100000).fit(Xs[tr], Y[tr])
            pr_ = np.atleast_2d(m_.predict(Xs[i:i + 1]))
            press[c - 1] += (Y[i] - pr_[0]) ** 2
    arr(f"PLS_{tag}_PRESS", press)
    # explained X variance (cumulative, of scaled X)
    Xc = Xs - Xs.mean(0)
    if scale:
        Xc = Xc / Xc.std(0, ddof=1)
    tt = (pl.x_scores_ ** 2).sum(0) * (pl.x_loadings_ ** 2).sum(0)
    arr(f"PLS_{tag}_XVAR", np.cumsum(tt) / np.sum(Xc ** 2))

