"""Reference values for tests/timeseries.rs (NumPy / SciPy; no time-series package is used).

Run: python3 ts_ref.py > ../common/ts_data.rs

* ACF / PACF / Ljung-Box: direct sums, Yule-Walker solves, scipy.stats.chi2.
* ARMA / ARIMA maximum likelihood: the exact Gaussian likelihood is evaluated from the full
  autocovariance matrix (psi-weight autocovariances + Cholesky), which shares no code or algorithm
  with the Kalman filter used in Rust; the optimum is found with scipy.optimize (BFGS + Nelder-Mead).
* Forecasts: exact best linear prediction from the same covariance matrix, and psi-weight standard
  errors with the integrated operator.
* Exponential smoothing: independent recursions, a brute-force grid for the SSE minimum.
* Decomposition: direct regression / averaging.
"""
import numpy as np
