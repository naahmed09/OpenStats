rng = np.random.default_rng(20261118)


def arr(name, a, ty="f64"):
    flat = ", ".join(repr(float(v)) for v in np.ravel(a))
    return f"pub const {name}: &[{ty}] = &[{flat}];\n"


def sc(name, v):
    return f"pub const {name}: f64 = {float(v)!r};\n"


def simulate_arma(n, phi, theta, mu=0.0, burn=300, sigma=1.0):
    e = rng.normal(0, sigma, n + burn)
    x = np.zeros(n + burn)
    for t in range(n + burn):
        v = e[t]
        for i, p in enumerate(phi):
            if t - 1 - i >= 0:
                v += p * x[t - 1 - i]
        for j, th in enumerate(theta):
            if t - 1 - j >= 0:
                v -= th * e[t - 1 - j]
        x[t] = v
    return x[burn:] + mu


def psi_weights(ar, ma, m):
    """psi of MA(B)/AR(B) with AR = 1 - sum ar_i B^i and MA = 1 - sum ma_j B^j."""
    psi = np.zeros(m)
    psi[0] = 1.0
    for j in range(1, m):
        v = -ma[j - 1] if j <= len(ma) else 0.0
        for i, a in enumerate(ar):
            if j - 1 - i >= 0:
                v += a * psi[j - 1 - i]
        psi[j] = v
    return psi


def acov_arma(ar, ma, nlag, M=4000):
    psi = psi_weights(ar, ma, M)
    return np.array([np.dot(psi[: M - k], psi[k:]) for k in range(nlag)])


def poly_expand(c, sc_, period):
    a = np.zeros(len(c) + len(sc_) * period + 1)
    a[0] = 1
    A = np.zeros(len(c) + 1); A[0] = 1
    for i, v in enumerate(c): A[i + 1] = -v
    B = np.zeros(len(sc_) * period + 1); B[0] = 1
    for j, v in enumerate(sc_): B[(j + 1) * period] = -v
    a = np.convolve(A, B)
    return -a[1:]


def exact_nll(params, w, p, q, sp, sq, period, mean):
    k = 0
    phi = params[k:k + p]; k += p
    th = params[k:k + q]; k += q
    sphi = params[k:k + sp]; k += sp
    sth = params[k:k + sq]; k += sq
    mu = params[k] if mean else 0.0
    ar = poly_expand(phi, sphi, period)
    ma = poly_expand(th, sth, period)
    # stationarity / invertibility
    def ok(c):
        if len(c) == 0: return True
        r = np.roots(np.r_[1, -c])
        return np.all(np.abs(r) < 1 - 1e-6)
    if not (ok(ar) and ok(ma)):
        return 1e10
    n = len(w)
    g = acov_arma(ar, ma, n)
    S = linalg.toeplitz(g)
    try:
        L = np.linalg.cholesky(S)
    except np.linalg.LinAlgError:
        return 1e10
    z = linalg.solve_triangular(L, w - mu, lower=True)
    quad = z @ z
    s2 = quad / n
    return 0.5 * (n * np.log(s2) + 2 * np.sum(np.log(np.diag(L))))


def fit_exact(w, p, q, sp, sq, period, mean):
    k = p + q + sp + sq + (1 if mean else 0)
    x0 = np.zeros(k)
    if mean: x0[-1] = w.mean()
    f = lambda x: exact_nll(x, w, p, q, sp, sq, period, mean)
    best = None
    for start in [x0, x0 + 0.1 * rng.normal(size=k) * (np.r_[np.ones(k - 1), 0] if mean else 1)]:
        r = optimize.minimize(f, start, method="Nelder-Mead", options=dict(xatol=1e-9, fatol=1e-12, maxiter=20000, maxfev=20000))
        r = optimize.minimize(f, r.x, method="BFGS", options=dict(gtol=1e-9))
        r = optimize.minimize(f, r.x, method="Nelder-Mead", options=dict(xatol=1e-10, fatol=1e-13, maxiter=20000, maxfev=20000))
        if best is None or r.fun < best.fun: best = r
    x = best.x
    n = len(w)
    return x, best.fun


def exact_forecast_w(w, params, p, q, sp, sq, period, mean, h):
    k = 0
    phi = params[k:k + p]; k += p
    th = params[k:k + q]; k += q
    sphi = params[k:k + sp]; k += sp
    sth = params[k:k + sq]; k += sq
    mu = params[k] if mean else 0.0
    ar = poly_expand(phi, sphi, period)
    ma = poly_expand(th, sth, period)
    n = len(w)
    g = acov_arma(ar, ma, n + h)
    S = linalg.toeplitz(g[:n])
    out = []
    for j in range(1, h + 1):
        c = g[j: j + n][::-1]  # cov(w_{n+j}, w_t) for t=1..n -> lag n+j-t
        c = np.array([g[n + j - 1 - t] for t in range(n)])
        out.append(mu + c @ np.linalg.solve(S, w - mu))
    return np.array(out)


