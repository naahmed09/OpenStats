def add_case(name, y, p, q_, sp, sq, per, mean, d=0, sd=0, h=6):
    w = y.copy()
    for _ in range(d): w = np.diff(w)
    for _ in range(sd): w = w[per:] - w[:-per]
    xhat, nll = fit_exact(w, p, q_, sp, sq, per, mean)
    n = len(w)
    # sigma2 and loglik at optimum
    k = 0
    phi = xhat[k:k + p]; k += p
    th = xhat[k:k + q_]; k += q_
    sphi = xhat[k:k + sp]; k += sp
    sth = xhat[k:k + sq]; k += sq
    mu = xhat[k] if mean else 0.0
    ar = poly_expand(phi, sphi, per); ma = poly_expand(th, sth, per)
    g = acov_arma(ar, ma, n)
    L = np.linalg.cholesky(linalg.toeplitz(g))
    z = linalg.solve_triangular(L, w - mu, lower=True)
    s2 = (z @ z) / n
    ll = -0.5 * (n * np.log(2 * np.pi * s2) + 2 * np.sum(np.log(np.diag(L))) + n)
    fw = exact_forecast_w(w, xhat, p, q_, sp, sq, per, mean, h)
    # integrate forecasts to the original scale
    full = list(y)
    wf = list(w)
    # reconstruct: forecasts of y by undoing differences
    yy = list(y)
    ww_all = list(w) + list(fw)
    # differencing operator coefficients
    delta = np.array([1.0])
    for _ in range(d): delta = np.convolve(delta, [1, -1])
    for _ in range(sd):
        s_ = np.zeros(per + 1); s_[0] = 1; s_[per] = -1
        delta = np.convolve(delta, s_)
    # y_t = w_t - sum_{i>=1} delta_i y_{t-i}
    for j in range(h):
        t = len(yy)
        v = ww_all[len(w) + j]
        for i in range(1, len(delta)):
            if t - i >= 0: v -= delta[i] * yy[t - i]
        yy.append(v)
    yf = np.array(yy[len(y):])
    # psi weights of MA(B)/(AR(B) delta(B))
    full_ar = -np.convolve(np.r_[1, -ar], delta)[1:]
    psi = psi_weights(full_ar, ma, h)
    se = np.sqrt(s2 * np.cumsum(psi ** 2))
    nparams = len(xhat) + 1
    aic = -2 * ll + 2 * nparams
    out.append(arr(f"{name}_Y", y))
    out.append(arr(f"{name}_PARAMS", xhat))
    out.append(sc(f"{name}_S2", s2))
    out.append(sc(f"{name}_LL", ll))
    out.append(sc(f"{name}_AIC", aic))
    out.append(arr(f"{name}_FC", yf))
    out.append(arr(f"{name}_FCSE", se))

