def init_hw(y, m, mult, trend=True):
    n = len(y)
    seasons = min(n // m, 3)
    mean_of = lambda i: y[i * m:(i + 1) * m].mean()
    first = mean_of(0)
    slope = (mean_of(seasons - 1) - first) / ((seasons - 1) * m) if (seasons >= 2 and trend) else 0.0
    level = first - slope * ((m - 1) / 2 + 1)
    s = np.zeros(m)
    for j in range(m):
        acc = 0
        for i in range(seasons):
            tt = i * m + j
            base = level + slope * (tt + 1)
            acc += y[tt] / base if mult else y[tt] - base
        s[j] = acc / seasons
    s = s / s.mean() if mult else s - s.mean()
    return level, slope, s

def hw(y, m, mult, a, b, g):
    level, tr, s = init_hw(y, m, mult)
    s = s.copy()
    n = len(y)
    fit = np.zeros(n)
    for t in range(n):
        st = s[t % m]
        base = level + tr
        fit[t] = base * st if mult else base + st
        l_new = a * (y[t] / st if mult else y[t] - st) + (1 - a) * base
        tr = b * (l_new - level) + (1 - b) * tr
        s[t % m] = g * (y[t] / l_new if mult else y[t] - l_new) + (1 - g) * st
        level = l_new
    fcs = []
    for j in range(1, 13):
        base = level + j * tr
        sj = s[(n + j - 1) % m]
        fcs.append(base * sj if mult else base + sj)
    return fit, np.array(fcs), np.sum((y - fit) ** 2)

